// Run only against a disposable local preview origin. This drives actual Blazor DOM
// events and validates visible results; it does not call internal tracker methods.
async function runPokedexUiChecks() {
    let checks = 0;
    const check = (condition, message) => { if (!condition) throw new Error(message); checks++; };
    const wait = async (condition, message) => {
        const start = Date.now();
        while (!condition()) {
            if (Date.now() - start > 8000) throw new Error(message);
            await new Promise(resolve => setTimeout(resolve, 50));
        }
    };
    const click = selector => { const element = document.querySelector(selector); if (!element) throw new Error('Missing ' + selector); element.focus(); element.click(); };
    const change = (selector, value, event = 'change') => { const element = document.querySelector(selector); element.value = value; element.dispatchEvent(new Event(event, { bubbles: true })); };
    const title = () => document.querySelector('main h1')?.textContent;
    const ready = () => !!document.querySelector('.sidebar') && !document.querySelector('.create-tracker')?.disabled;
    const expandSidebar = async () => { if (document.getElementById('tracker-navigation').hidden) { click('.sidebar-toggle'); await wait(() => !document.getElementById('tracker-navigation').hidden, 'Sidebar did not expand.'); } };
    const selectTracker = async trackerName => {
        await expandSidebar();
        [...document.querySelectorAll('.tracker-item')].find(button => button.querySelector('strong').textContent === trackerName).click();
    };
    const name = 'Verification ' + Date.now();
    await wait(ready, 'The published app did not finish startup.');
    const originalCount = document.querySelectorAll('.tracker-item').length;
    if (!document.getElementById('tracker-navigation').hidden) click('.sidebar-toggle');
    await wait(() => document.getElementById('tracker-navigation').hidden, 'Sidebar did not collapse.');
    check(document.querySelector('.sidebar').getBoundingClientRect().width === 64 && [...document.querySelectorAll('.sidebar button')].filter(button => button.checkVisibility()).length === 2, 'Collapsed sidebar has only Expand and Settings.');
    click('.settings-button');
    await wait(() => document.getElementById('settings-dialog').open, 'Collapsed Settings did not open.');
    click('#settings-dialog .dialog-actions button');
    await wait(() => !document.getElementById('settings-dialog').open, 'Settings did not close.');
    check(document.activeElement === document.querySelector('.settings-button'), 'Settings returns focus to its gear button.');
    await expandSidebar();
    check(document.querySelector('.sidebar-toggle').getAttribute('aria-expanded') === 'true', 'Expanded navigation exposes trackers and creation.');
    click('.create-tracker');
    await wait(() => document.querySelector('#create-dialog').open, 'New tracker dialog did not open.');
    check(document.querySelector('[aria-label="Game"]').options.length === 13, 'All supported editions can be selected.');
    change('[aria-label="Game"]', 'legends-za');
    await wait(() => [...document.querySelector('[aria-label="Pokédex"]').options].some(option => option.value === 'hyperspace'), 'Hyperspace is unavailable.');
    check([...document.querySelector('[aria-label="Pokédex"]').options].some(option => option.value === 'za-complete'), 'Z-A complete can be selected.');
    change('[aria-label="Game"]', 'scarlet');
    await wait(() => document.querySelector('[aria-label="Pokédex"]').value === 'paldea', 'Paldea selection did not update.');
    change('#create-dialog input', name);
    click('#create-dialog button[type="submit"]');
    await wait(() => title() === name && ready(), 'Tracker creation failed.');
    await wait(() => !document.querySelector('#create-dialog').open, 'Creation dialog did not close.');
    click('[aria-label="Tracker view"] button:first-child');
    await wait(() => document.querySelector('.pokemon-box'), 'Checklist view did not open.');
    check(document.querySelector('[aria-label="Tracker view"] button:first-child').getAttribute('aria-pressed') === 'true', 'The checklist view exposes its selected state.');
    check(document.querySelector('.pokemon-box .box-heading h2').textContent === '001-030', 'Main boxes use position ranges.');
    check([...document.querySelectorAll('.box-heading h2')].some(heading => heading.textContent === '391-400') && [...document.querySelectorAll('.box-heading h2')].some(heading => heading.textContent === 'Extra forms · Box 01'), 'Partial main box ranges and extra-form labels are correct.');
    check(document.querySelector('.box-grid').children.length === 30, 'The first box has 30 positions.');
    const cell = document.querySelector('[aria-label="Mark Sprigatito"]').closest('.pokemon-slot');
    const input = cell.querySelector('input');
    for (const target of [cell.querySelector('.pokemon-check'), cell.querySelector('img'), cell.querySelector('.slot-number'), cell.querySelector('.form-label'), cell.querySelector('.pokemon-name')]) {
        target.click();
        await wait(() => input.checked && ready(), 'Clicking a cell area did not check the Pokémon.');
        check(input.checked, 'The cell background, sprite, number, form, and name can each check the Pokémon.');
        target.click();
        await wait(() => !input.checked && ready(), 'Clicking a cell area did not uncheck the Pokémon.');
        check(!input.checked, 'Cell clicks toggle once and can uncheck the Pokémon.');
    }
    click('[aria-label="Mark Sprigatito"]');
    await wait(ready, 'Check did not save.');
    await wait(() => document.querySelector('[aria-label="Mark Sprigatito"]').closest('.pokemon-slot').classList.contains('is-checked'), 'Checked styling did not update.');
    const checkedSlot = document.querySelector('[aria-label="Mark Sprigatito"]').closest('.pokemon-slot');
    check(getComputedStyle(checkedSlot.querySelector('img')).filter === 'none' && getComputedStyle(document.querySelector('[aria-label="Mark Fuecoco"]').closest('.pokemon-slot').querySelector('img')).filter === 'grayscale(1)', 'Checked cards have colored sprites; unchecked sprites are grayscale.');
    click('[aria-label="Sources for Sprigatito"]');
    await wait(() => !!document.querySelector('#sources-panel'), 'Source panel did not open.');
    check(document.querySelector('#sources-panel').innerText.includes('Starter') && document.querySelector('#sources-panel a').href === 'https://www.serebii.net/pokedex-sv/sprigatito/', 'Acquisition information links to the correct species.');
    const panel = document.getElementById('sources-panel');
    check(!document.querySelector('dialog[open]'), 'Sources open alongside the checklist without a modal.');
    check(input.checked && !document.querySelector('[aria-label="Mark Fuecoco"]').checked, 'The sources button does not change checklist progress.');
    click('[aria-label="Sources for Fuecoco"]');
    await wait(() => document.querySelector('#info-title').textContent === 'Fuecoco', 'The panel did not update.');
    check(panel === document.getElementById('sources-panel'), 'Another source selection reuses the same panel.');
    check(!document.querySelector('[aria-label="Mark Fuecoco"]').checked, 'Viewing an unchecked Pokémon’s sources leaves it unchecked.');
    click('[aria-label="Close sources"]');
    await wait(() => !document.querySelector('#sources-panel'), 'Source panel did not close.');
    click('[aria-label="Sources for Sprigatito"]');
    await wait(() => !!document.getElementById('sources-panel'), 'Source panel did not reopen.');
    await wait(() => document.activeElement.closest('#sources-panel'), 'Panel heading did not receive focus.');
    document.activeElement.dispatchEvent(new KeyboardEvent('keydown', {key: 'Escape', bubbles: true}));
    await wait(() => !document.getElementById('sources-panel'), 'Escape did not close the panel.');
    check(document.activeElement === document.querySelector('[aria-label="Sources for Sprigatito"]'), 'Escape closes sources and returns focus to the opener.');
    change('input[type="search"]', 'wooper', 'input');
    check(document.querySelectorAll('.pokemon-slot:not(.filtered-out)').length === 2 && document.querySelector('.box-grid').children.length === 30, 'Search preserves box positions for both Wooper forms.');
    change('input[type="search"]', '', 'input');
    click('[aria-label="Pokémon completion filter"] button:nth-child(2)');
    check(document.querySelectorAll('.pokemon-slot:not(.filtered-out)').length === 1, 'Checked filter shows the marked Pokémon.');
    click('[aria-label="Pokémon completion filter"] button:nth-child(1)');
    await expandSidebar();
    click('.settings-button');
    await wait(() => document.querySelector('#settings-dialog').open, 'Settings did not open.');
    check(document.querySelector('#settings-dialog .sync-panel') && document.querySelector('#settings-dialog .backup-panel') && !document.querySelector('.app-header select'), 'Settings contains storage and appearance controls.');
    const originalTheme = document.querySelector('[aria-label="Theme"]').value;
    change('[aria-label="Theme"]', 'catppuccin');
    await wait(() => document.documentElement.dataset.theme === 'catppuccin', 'Catppuccin did not apply.');
    change('[aria-label="Color scheme"]', 'dark');
    await wait(() => document.documentElement.dataset.colorScheme === 'dark', 'Dark mode did not apply.');
    check(getComputedStyle(document.body).backgroundColor === 'rgb(30, 30, 46)', 'Dark mode uses Mocha.');
    change('[aria-label="Color scheme"]', 'light');
    await wait(() => document.documentElement.dataset.colorScheme === 'light', 'Light mode did not apply.');
    check(getComputedStyle(document.body).backgroundColor === 'rgb(239, 241, 245)', 'Light mode uses Latte.');
    change('[aria-label="Color scheme"]', 'system');
    await wait(() => document.documentElement.dataset.colorScheme === 'system', 'System mode did not apply.');
    check(getComputedStyle(document.body).backgroundColor === (matchMedia('(prefers-color-scheme: dark)').matches ? 'rgb(30, 30, 46)' : 'rgb(239, 241, 245)'), 'System mode follows the browser preference.');
    change('[aria-label="Theme"]', originalTheme);
    await wait(() => document.documentElement.dataset.theme === originalTheme, 'The original theme did not restore.');
    click('#settings-dialog .dialog-actions button');
    await wait(() => !document.querySelector('#settings-dialog').open, 'Settings did not close.');
    check(document.activeElement === document.querySelector('.settings-button'), 'Closing settings returns focus to its gear button.');
    document.querySelector('.tracker-actions').open = true;
    click('.tracker-actions button:nth-child(2)');
    await wait(() => title() === name + ' copy' && ready(), 'Duplicate did not appear.');
    check(document.querySelector('[aria-label="Mark Sprigatito"]').checked, 'Duplicate starts with copied checks.');
    click('[aria-label="Mark Sprigatito"]');
    await wait(ready, 'Duplicate check did not save.');
    await selectTracker(name);
    check(document.querySelector('[aria-label="Mark Sprigatito"]').checked, 'Editing a duplicate leaves its original unchanged.');
    document.querySelector('.tracker-actions').open = true;
    click('.tracker-actions button:nth-child(1)');
    await wait(() => document.querySelector('#action-dialog').open, 'Rename dialog did not open.');
    change('#action-dialog input', name + ' renamed');
    click('#action-dialog button[type="submit"]');
    await wait(() => title() === name + ' renamed' && ready(), 'Rename did not persist.');
    await wait(() => !document.querySelector('#action-dialog').open, 'Rename dialog did not close.');
    check(document.querySelector('[aria-label="Mark Sprigatito"]').checked, 'Renaming preserves checks.');
    document.querySelector('.tracker-actions').open = true;
    click('.tracker-actions button:nth-child(3)');
    await wait(() => document.querySelector('#action-dialog').open, 'Reset dialog did not open.');
    click('#action-dialog button[type="button"]');
    await wait(() => !document.querySelector('#action-dialog').open, 'Canceled reset dialog did not close.');
    check(document.querySelector('[aria-label="Mark Sprigatito"]').checked, 'Canceling reset preserves checks.');
    click('.tracker-actions button:nth-child(3)');
    await wait(() => document.querySelector('#action-dialog').open, 'Reset dialog did not reopen.');
    click('#action-dialog button[type="submit"]');
    await wait(ready, 'Reset did not save.');
    await wait(() => !document.querySelector('#action-dialog').open, 'Reset dialog did not close.');
    check(!document.querySelector('[aria-label="Mark Sprigatito"]').checked, 'Confirmed reset clears checks.');
    const names = [name + ' renamed', name + ' copy'];
    for (const trackerName of names) {
        await selectTracker(trackerName);
        document.querySelector('.tracker-actions').open = true;
        click('.tracker-actions button:nth-child(4)');
        await wait(() => document.querySelector('#action-dialog').open, 'Delete dialog did not open.');
        click('#action-dialog button[type="button"]');
        await wait(() => !document.querySelector('#action-dialog').open, 'Canceled delete dialog did not close.');
        check(title() === trackerName, 'Canceling deletion preserves the tracker.');
        click('.tracker-actions button:nth-child(4)');
        await wait(() => document.querySelector('#action-dialog').open, 'Delete dialog did not reopen.');
        click('#action-dialog button[type="submit"]');
        await wait(() => ![...document.querySelectorAll('.tracker-item')].some(button => button.querySelector('strong').textContent === trackerName), 'Confirmed deletion failed.');
        await wait(() => !document.querySelector('#action-dialog').open && ready(), 'Delete dialog did not finish closing.');
    }
    check(document.querySelectorAll('.tracker-item').length === originalCount, 'Control tests remove only their own trackers.');
    return { passed: checks, events: 'Actual Blazor DOM events', origin: location.origin };
}
runPokedexUiChecks();
